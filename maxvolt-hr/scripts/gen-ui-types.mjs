// Generates loose type stubs (src/types/ui/*.d.ts) for the shadcn components in src/components/ui.
// Why: they are untyped JS wrapped in React.forwardRef, so the editor's JS type-check (jsconfig "checkJs") infers their
// props as "ref only" and flags every <Button className=…> / <Card> / <Badge variant=…> in the app (thousands of errors).
// jsconfig.json maps "@/components/ui/*" to these stubs for the editor only — Vite still bundles the real components.
// Re-run after adding or renaming a UI component:  node scripts/gen-ui-types.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const uiDir = path.join(root, '..', 'src', 'components', 'ui');
const outDir = path.join(root, '..', 'src', 'types', 'ui');
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

let count = 0;
for (const file of fs.readdirSync(uiDir).filter(f => /\.(jsx?|tsx?)$/.test(f))) {
  const src = fs.readFileSync(path.join(uiDir, file), 'utf8');
  const names = new Set();
  for (const m of src.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const part of m[1].split(',')) {
      const t = part.trim(); if (!t) continue;
      const asMatch = t.match(/\bas\s+([A-Za-z0-9_$]+)\s*$/);
      names.add(asMatch ? asMatch[1] : t.replace(/^type\s+/, ''));
    }
  }
  for (const m of src.matchAll(/export\s+(?:const|let|var|function|class)\s+([A-Za-z0-9_$]+)/g)) names.add(m[1]);
  const hasDefault = /export\s+default\b/.test(src) || /export\s*\{[^}]*\bas\s+default\b/.test(src);
  const lines = [`// generated by scripts/gen-ui-types.mjs — do not edit`];
  for (const n of [...names].filter(n => n !== 'default')) lines.push(`export declare const ${n}: any;`);
  if (hasDefault) lines.push('declare const _default: any;', 'export default _default;');
  fs.writeFileSync(path.join(outDir, file.replace(/\.(jsx?|tsx?)$/, '.d.ts')), lines.join('\n') + '\n');
  count++;
}
console.log(`wrote ${count} UI type stubs to src/types/ui`);
